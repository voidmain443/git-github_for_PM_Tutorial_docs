def enrich_lesson(lesson, unit):
    """Add authored teaching sections, introductions, and concept self-checks.

    Existing identity, source links, documents, stage and process mappings are
    untouched. HTML is deliberately not updated here. Repeated calls replace
    this module's own layers, so regeneration does not duplicate paragraphs.
    The correct option index is zero-based; quizzes assess reasoning rather
    than supplying completed project deliverables.
    """
    unit = int(unit)
    if unit not in CHAPTERS:
        raise ValueError(f'Unsupported Level 1 unit: {unit}')
    lesson['chapterIntro'] = [list(section) for section in CHAPTERS[unit]]
    for step in lesson['guideSteps']:
        key = step['id']
        if key not in DEEP:
            raise KeyError(f'Missing authored explanation for unit {unit}, step {key}')
        material = DEEP[key]
        headings = {heading for heading, _ in material['sections']}
        base = [section for section in step['sections'] if section[0] not in headings]
        # Put the conceptual layer immediately after the opening explanation;
        # place reasoning before the existing partial example, and the transfer
        # paragraph before the final next-step prompt.
        base.insert(min(1, len(base)), list(material['sections'][0]))
        example_at = next((i for i, (h, _) in enumerate(base)
                           if '예제' in h or '예시' in h), min(4, len(base)))
        base.insert(example_at, list(material['sections'][1]))
        transfer_at = next((i for i, (h, _) in enumerate(base)
                            if h in ('다음에 이어 할 일', '단원 마무리')), len(base))
        base.insert(transfer_at, list(material['sections'][2]))
        step['sections'] = base
        step['selfCheck'] = {
            **material['selfCheck'],
            'options': list(material['selfCheck']['options']),
        }
    return lesson

